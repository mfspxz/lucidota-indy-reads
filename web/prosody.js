/* ============================================================================
 * Prosody — deterministic persona → voice-attribute mapping for Indy_Reads.
 *
 * window.Prosody maps (era, tone, position-in-utterance) → voice attributes
 * { rate, pitch, pause_ms, emphasis }. Pure function: no DOM, no Math.random,
 * no Date. Same input → same output, always. The parent (voice.js) calls
 * Prosody.attrs() and passes the result where it already passes
 * { rate, pitch, pause_ms } today — no integration surgery required.
 *
 * --- THE WARDROBE: 3 eras × 4 tones × 5 positions = 60 combos ---------------
 *
 * Era bases (measured live on the war-room attack turn, steel tone, 15:05):
 *   rookie   rate 0.934  pitch 0.969  pause  720ms   '93 bright/quick
 *   prime    rate 0.865  pitch 0.865  pause  850ms   '98 dry/measured
 *   veteran  rate 0.778  pitch 0.744  pause 1000ms   older low/weighty
 * Strictly ordered: rookie > prime > veteran on every axis. Voice IDs V-007-R/P/V.
 *
 * Tone modifiers (multiplicative flavor; tested to never move the emphasis
 * target — emphasis is computed from the text alone, tone-independent):
 *   dry       rate ×1.00  pitch ×1.00  pause ×1.00  (default)
 *   clinical  rate ×1.06  pitch ×0.97  pause ×0.90  faster, flatter
 *   warm      rate ×0.96  pitch ×1.04  pause ×1.10  slower, warmer
 *   steel     rate ×0.93  pitch ×0.94  pause ×1.25  slower, lower, weighty
 *
 * Position curve (where the segment sits in the utterance):
 *   opening   rate ×1.04  pitch ×1.02  pause   +0ms  leaning in
 *   early     rate ×1.01  pitch ×1.00  pause  +50ms
 *   middle    rate ×1.00  pitch ×1.00  pause +100ms
 *   late      rate ×0.97  pitch ×0.98  pause +150ms
 *   closing   rate ×0.92  pitch ×0.95  pause +250ms  landing the point
 *
 * Final = round3(clamp(era_base × tone_mod × pos_mod)), pause clamped 0–3000ms.
 * Unknown era → 'prime', unknown tone → 'dry', unknown position → 'middle'
 * (forgiving parse, same doctrine as the /api/turn era/tone handling).
 *
 * Full 60-combo table (rate/pitch/pause_ms), generated by Prosody.wardrobe():
 *
 *  rookie/dry:           opening 0.971/0.988/720    early   0.943/0.969/770
 *                    middle  0.934/0.969/820    late    0.906/0.950/870
 *                    closing 0.859/0.921/970
 *  rookie/clinical:      opening 1.030/0.959/648    early   1.000/0.940/698
 *                    middle  0.990/0.940/748    late    0.960/0.921/798
 *                    closing 0.911/0.893/898
 *  rookie/warm:          opening 0.933/1.028/792    early   0.906/1.008/842
 *                    middle  0.897/1.008/892    late    0.870/0.988/942
 *                    closing 0.825/0.957/1042
 *  rookie/steel:         opening 0.903/0.929/900    early   0.877/0.911/950
 *                    middle  0.869/0.911/1000    late    0.843/0.893/1050
 *                    closing 0.799/0.865/1150
 *  prime/dry:            opening 0.900/0.882/850    early   0.874/0.865/900
 *                    middle  0.865/0.865/950    late    0.839/0.848/1000
 *                    closing 0.796/0.822/1100
 *  prime/clinical:       opening 0.954/0.856/765    early   0.926/0.839/815
 *                    middle  0.917/0.839/865    late    0.889/0.822/915
 *                    closing 0.844/0.797/1015
 *  prime/warm:           opening 0.864/0.918/935    early   0.839/0.900/985
 *                    middle  0.830/0.900/1035    late    0.805/0.882/1085
 *                    closing 0.764/0.855/1185
 *  prime/steel:          opening 0.837/0.829/1063    early   0.812/0.813/1113
 *                    middle  0.804/0.813/1163    late    0.780/0.797/1213
 *                    closing 0.740/0.772/1313
 *  veteran/dry:          opening 0.809/0.759/1000    early   0.786/0.744/1050
 *                    middle  0.778/0.744/1100    late    0.755/0.729/1150
 *                    closing 0.716/0.707/1250
 *  veteran/clinical:     opening 0.858/0.736/900    early   0.833/0.722/950
 *                    middle  0.825/0.722/1000    late    0.800/0.707/1050
 *                    closing 0.759/0.686/1150
 *  veteran/warm:         opening 0.777/0.789/1100    early   0.754/0.774/1150
 *                    middle  0.747/0.774/1200    late    0.724/0.758/1250
 *                    closing 0.687/0.735/1350
 *  veteran/steel:        opening 0.752/0.713/1250    early   0.731/0.699/1300
 *                    middle  0.724/0.699/1350    late    0.702/0.685/1400
 *                    closing 0.666/0.664/1500
 *
 * Emphasis: the longest alphabetic word in the segment (ties → first
 * occurrence). Deterministic, text-derived, tone-independent by construction.
 * ========================================================================== */
(function () {
  'use strict';

  var ERAS = ['rookie', 'prime', 'veteran'];
  var TONES = ['dry', 'clinical', 'warm', 'steel'];
  var POSITIONS = ['opening', 'early', 'middle', 'late', 'closing'];

  var ERA_BASE = {
    rookie:  { rate: 0.934, pitch: 0.969, pause: 720 },
    prime:   { rate: 0.865, pitch: 0.865, pause: 850 },
    veteran: { rate: 0.778, pitch: 0.744, pause: 1000 },
  };

  var TONE_MOD = {
    dry:      { rate: 1.00, pitch: 1.00, pause: 1.00 },
    clinical: { rate: 1.06, pitch: 0.97, pause: 0.90 },
    warm:     { rate: 0.96, pitch: 1.04, pause: 1.10 },
    steel:    { rate: 0.93, pitch: 0.94, pause: 1.25 },
  };

  var POS_MOD = {
    opening: { rate: 1.04, pitch: 1.02, add: 0 },
    early:   { rate: 1.01, pitch: 1.00, add: 50 },
    middle:  { rate: 1.00, pitch: 1.00, add: 100 },
    late:    { rate: 0.97, pitch: 0.98, add: 150 },
    closing: { rate: 0.92, pitch: 0.95, add: 250 },
  };

  function normEra(e) { e = String(e || '').toLowerCase(); return ERAS.indexOf(e) >= 0 ? e : 'prime'; }
  function normTone(t) { t = String(t || '').toLowerCase(); return TONES.indexOf(t) >= 0 ? t : 'dry'; }
  function normPos(p) { p = String(p || '').toLowerCase(); return POSITIONS.indexOf(p) >= 0 ? p : 'middle'; }
  function clamp(v, lo, hi) { return v < lo ? lo : v > hi ? hi : v; }
  function r3(v) { return Math.round(v * 1000) / 1000; }

  // Longest alphabetic word in the text; ties resolve to first occurrence.
  // Tone-independent by construction — tones are flavor, never emphasis.
  function emphasisWord(text) {
    var words = String(text || '').match(/[A-Za-z][A-Za-z'\-]*/g) || [];
    var best = '', bestLen = 0;
    for (var i = 0; i < words.length; i++) {
      var w = words[i].replace(/^['\-]+|['\-]+$/g, '');
      if (w.length > bestLen) { best = w; bestLen = w.length; }
    }
    return best;
  }

  // Core mapping: (era, tone, position) -> voice attributes.
  function attrs(era, tone, position) {
    era = normEra(era); tone = normTone(tone); position = normPos(position);
    var b = ERA_BASE[era], tm = TONE_MOD[tone], pm = POS_MOD[position];
    return {
      era: era,
      tone: tone,
      position: position,
      rate: r3(clamp(b.rate * tm.rate * pm.rate, 0.5, 2.0)),
      pitch: r3(clamp(b.pitch * tm.pitch * pm.pitch, 0.0, 2.0)),
      pause_ms: Math.round(clamp(b.pause * tm.pause + pm.add, 0, 3000)),
    };
  }

  // attrs() plus emphasis for a concrete text segment.
  function attrsFor(text, era, tone, position) {
    var a = attrs(era, tone, position);
    a.emphasis = emphasisWord(text);
    return a;
  }

  // The full 60-combo wardrobe, for docs/slides/debugging.
  function wardrobe() {
    var out = [];
    for (var e = 0; e < ERAS.length; e++)
      for (var t = 0; t < TONES.length; t++)
        for (var p = 0; p < POSITIONS.length; p++)
          out.push(attrs(ERAS[e], TONES[t], POSITIONS[p]));
    return out;
  }

  // --- within-utterance era morphing ---------------------------------------
  // Deterministic segmentation: sentences first, then clause splits for long
  // sentences. Split points are punctuation boundaries only — no randomness,
  // no model calls. Era walks fromEra -> toEra across the segments on a
  // linear quantized schedule (rookie=0, prime=1, veteran=2), so
  // Rookie→Veteran passes through Prime mid-utterance: the party trick.
  var MAX_SEGMENTS = 8;

  function splitSegments(text) {
    text = String(text || '').trim();
    if (!text) return [];
    // 1. sentence boundaries (keep the delimiter on the sentence)
    var sentences = text.match(/[^.!?…]+[.!?…]+["”']?|\S[^.!?…]*$/g) || [text];
    var segs = [];
    for (var i = 0; i < sentences.length; i++) {
      var s = sentences[i].trim();
      if (!s) continue;
      // 2. long sentences split on clause boundaries
      if (s.length > 140) {
        var clauses = s.match(/[^,;:—–]+[,;:—–]+|[^,;:—–]+$/g) || [s];
        for (var j = 0; j < clauses.length; j++) {
          var c = clauses[j].trim();
          if (c) segs.push(c);
        }
      } else segs.push(s);
    }
    // 3. cap: merge the shortest adjacent pair until within budget
    while (segs.length > MAX_SEGMENTS) {
      var mi = 0, ml = Infinity;
      for (var k = 0; k < segs.length - 1; k++) {
        var L = segs[k].length + segs[k + 1].length;
        if (L < ml) { ml = L; mi = k; }
      }
      segs.splice(mi, 2, segs[mi] + ' ' + segs[mi + 1]);
    }
    return segs;
  }

  function morphPlan(text, fromEra, toEra, tone) {
    fromEra = normEra(fromEra); toEra = normEra(toEra); tone = normTone(tone);
    var segs = splitSegments(text);
    var fi = ERAS.indexOf(fromEra), ti = ERAS.indexOf(toEra);
    var n = segs.length;
    return segs.map(function (seg, i) {
      var p = n > 1 ? i / (n - 1) : 0;
      var eraIdx = Math.round(fi + (ti - fi) * p);
      eraIdx = Math.max(0, Math.min(ERAS.length - 1, eraIdx));
      var era = ERAS[eraIdx];
      var position = n === 1 ? 'middle' : (i === 0 ? 'opening' : (i === n - 1 ? 'closing' : 'middle'));
      return {
        index: i,
        text: seg,
        era: era,
        morph_t: Math.round(p * 1000) / 1000,
        attrs: attrsFor(seg, era, tone, position),
      };
    });
  }

  window.Prosody = {
    ERAS: ERAS.slice(),
    TONES: TONES.slice(),
    POSITIONS: POSITIONS.slice(),
    attrs: attrs,
    attrsFor: attrsFor,
    wardrobe: wardrobe,
    morphPlan: morphPlan,
    emphasisWord: emphasisWord,
  };
})();
